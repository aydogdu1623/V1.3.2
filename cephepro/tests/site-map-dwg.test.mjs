import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {database} from './helpers/test-db.mjs';
import {createSiteMapHandler} from '../api/site-map.js';
import {runCad} from '../lib/dwg-service.js';
const file=await readFile(new URL('../examples/verification-polygon.dwg',import.meta.url));
test('private multipart DWG converts real binary and saves only after review',async t=>{
 const d=await database(t),handler=createSiteMapHandler({...d.deps,config:()=>({})});
 const post=(action,b,user='founder')=>d.call(handler,'POST',user,{action,...b});
 const data=file.toString('base64'),start={name:'Villa.DWG',size:file.length};
 assert.equal((await post('upload-start',start,'member-a')).code,403);
 const {body:{id,engine}}=await post('upload-start',start);assert.equal(engine,'libredwg');
 assert.equal((await post('upload-finish',{id})).code,409);
 assert.equal((await post('upload-chunk',{id,index:0,data},'admin-a')).code,404);
 assert.equal((await post('upload-chunk',{id,index:0,data:'QUJD'})).code,400);
 for(let i=0;i<2;i++)assert.equal((await post('upload-chunk',{id,index:0,data})).code,200);
 const result=await post('upload-finish',{id});assert.equal(result.code,200,JSON.stringify(result.body));
 const {map}=result.body;assert.equal(map.source.format,'dwg');assert.equal(map.source.name,start.name);
 const feature=map.features.find(f=>f.kind==='building');assert.equal(feature.geometry.type,'Polygon');assert.ok(feature.components.length>0);
 const parts=await d.sql`SELECT count(*)::int AS n FROM cephepro_cad_parts`;assert.equal(parts[0].n,0);
 const state=(await d.call(handler,'GET','founder')).body;assert.equal(state.map.features.length,0);assert.equal(state.dwgReady,true);
 assert.equal((await d.call(handler,'GET','founder',null,{job:id})).body.status,'ready');
 assert.equal((await d.call(handler,'PUT','founder',{map,revision:state.revision})).code,200);
 assert.equal((await d.call(handler,'GET','founder')).body.map.source.name,'Villa.DWG');
 assert.equal((await post('upload-start',{...start,size:250_000_001})).code,413);
 const large=await post('upload-start',{...start,size:250_000_000});assert.equal(large.code,200);
 assert.equal((await post('upload-cancel',{id:large.body.id})).code,200);
 const me={role:'admin',id:'founder',projectId:'main'},bytes=Buffer.alloc(900013,42);file.copy(bytes);
 const job=await runCad(d.sql,me,'upload-start',{...start,size:bytes.length});
 for(const index of [1,0])await runCad(d.sql,me,'upload-chunk',{id:job.id,index,data:bytes.subarray(index*900000,(index+1)*900000).toString('base64')});
 const fresh=await runCad(d.sql,me,'upload-finish',{id:job.id},async input=>{assert.deepEqual(await readFile(input),bytes);return structuredClone(map);});assert.equal(fresh.status,'ready');
});
