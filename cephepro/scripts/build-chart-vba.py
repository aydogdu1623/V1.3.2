"""Build the audited chart-only VBA project. Build dependency: pyOpenVBA==6.6.0.

python -m pip install pyOpenVBA==6.6.0 XlsxWriter==3.2.9
python scripts/build-chart-vba.py
The application ships the generated JS; Python is not used by visitors/Vercel.
"""
import base64
import hashlib
import json
import tempfile
from pathlib import Path
from zipfile import ZipFile

import xlsxwriter
from pyopenvba import ExcelFile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'scripts/chart-vba'
SHEET_COUNT = 11

with tempfile.TemporaryDirectory() as folder:
    path = Path(folder) / 'chart.xlsm'
    with xlsxwriter.Workbook(str(path)) as seed:
        for index in range(1, SHEET_COUNT + 1):
            seed.add_worksheet(f'Sheet{index}')
    with ExcelFile(path) as book:
        project = book.add_vba_project()
        book.set_module('ThisWorkbook', (SOURCE / 'ThisWorkbook.cls').read_text().replace('\n', '\r\n'))
        project.add_module('CepheProChart', (SOURCE / 'CepheProChart.bas').read_text().replace('\n', '\r\n'))
        book.save()
    with ZipFile(path) as archive:
        data = archive.read('xl/vbaProject.bin')

payload = {'sheetCount': SHEET_COUNT, 'sha256': hashlib.sha256(data).hexdigest(), 'base64': base64.b64encode(data).decode()}
(ROOT / 'assets/report-chart-vba.js').write_text('// Generated by scripts/build-chart-vba.py; source: scripts/chart-vba/.\nwindow.CepheProChartVba=' + json.dumps(payload, separators=(',', ':')) + ';\n')
print(f'Chart VBA: {len(data)} bytes; sha256={payload["sha256"]}')
